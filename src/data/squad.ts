export type Pos = "GK" | "RB" | "CB" | "LB" | "CDM" | "CM" | "CAM" | "RW" | "LW" | "ST";

export interface Player {
  id: string;
  name: string;
  shortName: string;
  number: number;
  pos: Pos;
  role: string;
  nationality: string;
  age: number;
  overall: number;
  potential: number;
  fitness: number;
  morale: number; // 0-100
  form: number; // -3 .. +3 arrow scale mapped 0-100
  formTrend: "up" | "down" | "flat";
  attrs: {
    pace: number;
    shooting: number;
    passing: number;
    dribbling: number;
    defending: number;
    physical: number;
    // Extended attributes for goalkeeper and specialized positions
    reflexes?: number;
    handling?: number;
    distribution?: number;
    stamina?: number;
    crossing?: number;
    vision?: number;
    positioning?: number;
    heading?: number;
    strength?: number;
  };
  professionalism: number;
  personality: string;
  value: string;
  salary: string;
  contractUntil: string;
  contractYears: number;
  trainingFocus: string;
  trainingProgress: number; // % toward next overall point
  status?: "available" | "injured" | "suspended" | "retired";
  starter: boolean;
  // pitch coordinates in % (4-3-3)
  x?: number;
  y?: number;
}

